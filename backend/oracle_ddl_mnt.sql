CREATE TABLE DATA.T_MTTO_TIPOS_ACTIVO (
    ID_TIPO_ACTIVO  NUMBER          NOT NULL,
    CODIGO_COMPANIA VARCHAR2(10 BYTE) DEFAULT 'ZML_EC' NOT NULL,
    NOMBRE          VARCHAR2(100 BYTE) NOT NULL,
    DESCRIPCION     VARCHAR2(500 BYTE),
    CONSTRAINT T_MTTO_TIPOS_ACTIVO_PK PRIMARY KEY (ID_TIPO_ACTIVO)
);

CREATE TABLE DATA.T_MTTO_ESTADOS_ACTIVO (
    ID_ESTADO       NUMBER          NOT NULL,
    CODIGO_COMPANIA VARCHAR2(10 BYTE) DEFAULT 'ZML_EC' NOT NULL,
    NOMBRE          VARCHAR2(50 BYTE) NOT NULL,
    COLOR_HEX       VARCHAR2(7 BYTE),
    ES_OPERATIVO    VARCHAR2(1 BYTE) DEFAULT 'S',
    CONSTRAINT T_MTTO_ESTADOS_ACTIVO_PK PRIMARY KEY (ID_ESTADO)
);

CREATE TABLE DATA.T_MTTO_ESTADOS_OT (
    ID_ESTADO_OT    NUMBER          NOT NULL,
    CODIGO_COMPANIA VARCHAR2(10 BYTE) DEFAULT 'ZML_EC' NOT NULL,
    NOMBRE          VARCHAR2(50 BYTE) NOT NULL,
    CODIGO          VARCHAR2(20 BYTE) NOT NULL,
    COLOR_HEX       VARCHAR2(7 BYTE),
    ORDEN_KANBAN    NUMBER,
    ES_ESTADO_FINAL VARCHAR2(1 BYTE) DEFAULT 'N',
    CONSTRAINT T_MTTO_ESTADOS_OT_PK PRIMARY KEY (ID_ESTADO_OT)
);

CREATE TABLE DATA.T_MTTO_PRIORIDADES (
    ID_PRIORIDAD         NUMBER          NOT NULL,
    CODIGO_COMPANIA      VARCHAR2(10 BYTE) DEFAULT 'ZML_EC' NOT NULL,
    NOMBRE               VARCHAR2(50 BYTE) NOT NULL,
    NIVEL                NUMBER          NOT NULL,
    COLOR_HEX            VARCHAR2(7 BYTE),
    TIEMPO_RESPUESTA_HRS NUMBER,
    CONSTRAINT T_MTTO_PRIORIDADES_PK PRIMARY KEY (ID_PRIORIDAD)
);

CREATE TABLE DATA.T_ERP_REPUESTOS_VW (
    ID_REPUESTO     NUMBER          NOT NULL,
    CODIGO_COMPANIA VARCHAR2(10 BYTE) DEFAULT 'ZML_EC' NOT NULL,
    CODIGO_ERP      VARCHAR2(50 BYTE) NOT NULL,
    DESCRIPCION     VARCHAR2(300 BYTE) NOT NULL,
