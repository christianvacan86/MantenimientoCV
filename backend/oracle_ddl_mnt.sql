    CONSTRAINT T_MTTO_LECTURAS_PUNTO_FK  FOREIGN KEY (ID_PUNTO)
        REFERENCES DATA.T_MTTO_PUNTOS_MEDICION (ID_PUNTO)
);

CREATE TABLE DATA.T_MTTO_PLANES (
    ID_PLAN             NUMBER          NOT NULL,
    CODIGO_COMPANIA     VARCHAR2(10 BYTE) DEFAULT 'ZML_EC' NOT NULL,
    ID_ACTIVO           NUMBER          NOT NULL,
    NOMBRE              VARCHAR2(200 BYTE) NOT NULL,
    TIPO_FRECUENCIA     VARCHAR2(20 BYTE) NOT NULL,
    FRECUENCIA_VALOR    NUMBER          NOT NULL,
    ID_PUNTO_MEDICION   NUMBER,
    CONSTRAINT T_MTTO_PLANES_PK          PRIMARY KEY (ID_PLAN),
    CONSTRAINT T_MTTO_PLANES_ACTIVO_FK   FOREIGN KEY (ID_ACTIVO)
        REFERENCES DATA.T_MTTO_ACTIVOS (ID_ACTIVO),
    CONSTRAINT T_MTTO_PLANES_PUNTO_FK    FOREIGN KEY (ID_PUNTO_MEDICION)
        REFERENCES DATA.T_MTTO_PUNTOS_MEDICION (ID_PUNTO)
