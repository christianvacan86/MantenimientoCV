CREATE TABLE DATA.T_MTTO_TAREAS_PLAN (
    ID_TAREA_PLAN    NUMBER          NOT NULL,
    CODIGO_COMPANIA  VARCHAR2(10 BYTE) DEFAULT 'ZML_EC' NOT NULL,
    ID_PLAN          NUMBER          NOT NULL,
    SECUENCIA        NUMBER          NOT NULL,
    DESCRIPCION      VARCHAR2(1000 BYTE) NOT NULL,
    REQUIERE_MEDICION VARCHAR2(1 BYTE) DEFAULT 'N',
    CONSTRAINT T_MTTO_TAREAS_PLAN_PK     PRIMARY KEY (ID_TAREA_PLAN),
    CONSTRAINT T_MTTO_TAREAS_PLAN_FK     FOREIGN KEY (ID_PLAN)
        REFERENCES DATA.T_MTTO_PLANES (ID_PLAN)
);

CREATE TABLE DATA.T_MTTO_REPUESTOS_PLAN (
    ID_REPUESTO_PLAN NUMBER          NOT NULL,
    CODIGO_COMPANIA  VARCHAR2(10 BYTE) DEFAULT 'ZML_EC' NOT NULL,
    ID_PLAN          NUMBER          NOT NULL,
    ID_REPUESTO      NUMBER          NOT NULL,
    CANTIDAD         NUMBER          NOT NULL,
    CONSTRAINT T_MTTO_REPUESTOS_PLAN_PK  PRIMARY KEY (ID_REPUESTO_PLAN),
    CONSTRAINT T_MTTO_REP_PLAN_PLAN_FK   FOREIGN KEY (ID_PLAN)
        REFERENCES DATA.T_MTTO_PLANES (ID_PLAN),
    CONSTRAINT T_MTTO_REP_PLAN_REP_FK    FOREIGN KEY (ID_REPUESTO)
        REFERENCES DATA.T_ERP_REPUESTOS_VW (ID_REPUESTO)
);

CREATE TABLE DATA.T_MTTO_ORDENES_TRABAJO (
    ID_OT           NUMBER          NOT NULL,
    CODIGO_COMPANIA VARCHAR2(10 BYTE) DEFAULT 'ZML_EC' NOT NULL,
    NUMERO_OT       VARCHAR2(20 BYTE) NOT NULL,
    TIPO_OT         VARCHAR2(20 BYTE) NOT NULL,
    ID_PRIORIDAD    NUMBER          NOT NULL,
    ID_ESTADO_OT    NUMBER          NOT NULL,
    ID_ACTIVO       NUMBER          NOT NULL,
    DESCRIPCION     VARCHAR2(4000 BYTE) NOT NULL,
    FECHA_PROGRAMADA DATE,
    ASIGNADO_A      VARCHAR2(100 BYTE),
    CREADO_POR      VARCHAR2(100 BYTE) NOT NULL,
    FECHA_CREACION  DATE DEFAULT SYSDATE,
    CONSTRAINT T_MTTO_ORDENES_TRABAJO_PK  PRIMARY KEY (ID_OT),
    CONSTRAINT T_MTTO_OT_NUMERO_UK        UNIQUE (NUMERO_OT),
    CONSTRAINT T_MTTO_OT_PRIORIDAD_FK     FOREIGN KEY (ID_PRIORIDAD)
        REFERENCES DATA.T_MTTO_PRIORIDADES (ID_PRIORIDAD),
    CONSTRAINT T_MTTO_OT_ESTADO_FK        FOREIGN KEY (ID_ESTADO_OT)
        REFERENCES DATA.T_MTTO_ESTADOS_OT (ID_ESTADO_OT),
    CONSTRAINT T_MTTO_OT_ACTIVO_FK        FOREIGN KEY (ID_ACTIVO)
        REFERENCES DATA.T_MTTO_ACTIVOS (ID_ACTIVO)
);

CREATE TABLE DATA.T_MTTO_CHECKLIST_OT (
    ID_CHECKLIST        NUMBER          NOT NULL,
    CODIGO_COMPANIA     VARCHAR2(10 BYTE) DEFAULT 'ZML_EC' NOT NULL,
    ID_OT               NUMBER          NOT NULL,
    SECUENCIA           NUMBER          NOT NULL,
    DESCRIPCION         VARCHAR2(1000 BYTE) NOT NULL,
    COMPLETADO          VARCHAR2(1 BYTE) DEFAULT 'N',
    VALOR_MEDIDO        VARCHAR2(100 BYTE),
    OBSERVACION_TECNICO VARCHAR2(1000 BYTE),
    CONSTRAINT T_MTTO_CHECKLIST_OT_PK  PRIMARY KEY (ID_CHECKLIST),
    CONSTRAINT T_MTTO_CHECKLIST_OT_FK  FOREIGN KEY (ID_OT)
        REFERENCES DATA.T_MTTO_ORDENES_TRABAJO (ID_OT)
);

CREATE TABLE DATA.T_MTTO_SOLICITUDES (
    ID_SOLICITUD      NUMBER          NOT NULL,
    CODIGO_COMPANIA   VARCHAR2(10 BYTE) DEFAULT 'ZML_EC' NOT NULL,
    ID_ACTIVO         NUMBER          NOT NULL,
    DESCRIPCION_FALLA VARCHAR2(2000 BYTE) NOT NULL,
    PRIORIDAD_SUGERIDA VARCHAR2(50 BYTE),
    ESTADO            VARCHAR2(20 BYTE) DEFAULT 'PENDIENTE',
    REPORTADO_POR     VARCHAR2(100 BYTE) NOT NULL,
    FECHA_REPORTE     DATE DEFAULT SYSDATE,
    ID_OT_GENERADA    NUMBER,
    CONSTRAINT T_MTTO_SOLICITUDES_PK     PRIMARY KEY (ID_SOLICITUD),
    CONSTRAINT T_MTTO_SOL_ACTIVO_FK      FOREIGN KEY (ID_ACTIVO)
        REFERENCES DATA.T_MTTO_ACTIVOS (ID_ACTIVO),
    CONSTRAINT T_MTTO_SOL_OT_FK          FOREIGN KEY (ID_OT_GENERADA)
        REFERENCES DATA.T_MTTO_ORDENES_TRABAJO (ID_OT)
);

