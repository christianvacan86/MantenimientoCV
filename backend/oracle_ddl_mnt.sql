-- PASO 3: TABLAS PRINCIPALES
-- ============================================================

CREATE TABLE DATA.T_MTTO_ACTIVOS (
    ID_ACTIVO       NUMBER          NOT NULL,
    CODIGO_COMPANIA VARCHAR2(10 BYTE) DEFAULT 'ZML_EC' NOT NULL,
    CODIGO_ACTIVO   VARCHAR2(30 BYTE) NOT NULL,
    NOMBRE          VARCHAR2(200 BYTE) NOT NULL,
    DESCRIPCION     VARCHAR2(4000 BYTE),
    ID_TIPO_ACTIVO  NUMBER          NOT NULL,
    ID_ESTADO       NUMBER          NOT NULL,
    ID_ACTIVO_PADRE NUMBER,
    ID_PLANTA       NUMBER          NOT NULL,
    ID_AREA         NUMBER,
    ID_LINEA        NUMBER,
    NIVEL_JERARQUIA NUMBER          NOT NULL,
    CRITICIDAD      VARCHAR2(1 BYTE) DEFAULT 'C',
    MARCA           VARCHAR2(100 BYTE),
    MODELO          VARCHAR2(100 BYTE),
    NUMERO_SERIE    VARCHAR2(100 BYTE),
    ANIO_FABRICACION NUMBER,
    CREADO_POR      VARCHAR2(100 BYTE) NOT NULL,
    FECHA_CREACION  DATE DEFAULT SYSDATE,
    CONSTRAINT T_MTTO_ACTIVOS_PK      PRIMARY KEY (ID_ACTIVO),
    CONSTRAINT T_MTTO_ACTIVOS_UK      UNIQUE (CODIGO_ACTIVO),
    CONSTRAINT T_MTTO_ACTIVOS_TIPO_FK FOREIGN KEY (ID_TIPO_ACTIVO)
        REFERENCES DATA.T_MTTO_TIPOS_ACTIVO (ID_TIPO_ACTIVO),
    CONSTRAINT T_MTTO_ACTIVOS_EST_FK  FOREIGN KEY (ID_ESTADO)
        REFERENCES DATA.T_MTTO_ESTADOS_ACTIVO (ID_ESTADO),
    CONSTRAINT T_MTTO_ACTIVOS_PAD_FK  FOREIGN KEY (ID_ACTIVO_PADRE)
        REFERENCES DATA.T_MTTO_ACTIVOS (ID_ACTIVO)
);

CREATE TABLE DATA.T_MTTO_PUNTOS_MEDICION (
    ID_PUNTO        NUMBER          NOT NULL,
    CODIGO_COMPANIA VARCHAR2(10 BYTE) DEFAULT 'ZML_EC' NOT NULL,
    ID_ACTIVO       NUMBER          NOT NULL,
    NOMBRE          VARCHAR2(100 BYTE) NOT NULL,
    UNIDAD_MEDIDA   VARCHAR2(20 BYTE) NOT NULL,
    VALOR_ACUMULADO NUMBER DEFAULT 0,
    CONSTRAINT T_MTTO_PUNTOS_MEDICION_PK PRIMARY KEY (ID_PUNTO),
    CONSTRAINT T_MTTO_PUNTOS_ACTIVO_FK   FOREIGN KEY (ID_ACTIVO)
        REFERENCES DATA.T_MTTO_ACTIVOS (ID_ACTIVO)
);

CREATE TABLE DATA.T_MTTO_LECTURAS_USO (
    ID_LECTURA      NUMBER          NOT NULL,
    CODIGO_COMPANIA VARCHAR2(10 BYTE) DEFAULT 'ZML_EC' NOT NULL,
    ID_PUNTO        NUMBER          NOT NULL,
    VALOR_LEIDO     NUMBER          NOT NULL,
